COMPILED = [(re.compile(pattern), target) for pattern, target in RULES]


def route_of(row, votes):
    """Наш раздел для строки выгрузки поставщика.

    Сначала правила по дереву поставщика, и только потом — по названию товара:
    в названии каски встречается «из тканевых лент», и правило про ленты
    уводило её в скотч.
    """
    branch = norm(' '.join(filter(None, (row['PARENTID_NAME0'], row['PARENTID_NAME1'],
                                         row['PARENTID_NAME2']))))
    for pattern, target in COMPILED:
        if pattern.search(branch):
            return target
    with_name = f"{branch} {norm(row['NAIMEN'])}"
    for pattern, target in COMPILED:
        if pattern.search(with_name):
            return target

    group = votes[(row['PARENTID_NAME1'], row['PARENTID_NAME2'])]
    if group:
        return group.most_common(1)[0][0]

    second = (row['PARENTID_NAME1'] or '').strip()
    name = group_name(row['PARENTID_NAME2'] if second in BROAD else second or row['PARENTID_NAME2'])
    top = LEVEL1.get(row['PARENTID_NAME0'])
    if top and name:
        return f'{top} > {name} (новый подраздел)'
    if name:
        return f'— новый раздел: {group_name(row["PARENTID_NAME0"])} > {name} —'
    return UNSORTED


def catalog():
    """Товары витрины: адрес раздела, название и артикул."""
    source = CATALOG.read_text(encoding='utf-8')
    cats = json.loads(re.search(r'export const CATEGORIES: Category\[\] = (\[.*?\]);\n', source, re.S).group(1))
    products = json.loads(re.search(r'export const RAW_PRODUCTS[^=]*= (\[.*?\]);\n', source, re.S).group(1))
    names = {c['slug']: c['name'] for c in cats}
    subs = {s['slug']: s['name'] for c in cats for s in c['subcategories']}
    out = []
    for product in products:
        sku = next((s['value'] for s in product['specs'] if s['label'] == 'Артикул'), '')
        path = f"{names[product['categorySlug']]} > {subs.get(product['subcategorySlug'], '')}"
        out.append({'id': product['id'], 'sku': sku, 'title': product['title'], 'path': path})
    return out


def supplier():
    csv.field_size_limit(10 ** 7)
    with SUPPLIER.open(encoding='utf-8-sig', errors='replace', newline='') as f:
        return list(csv.DictReader(f, delimiter=';'))


def norm(text):
    return ' '.join((text or '').split()).lower()


# Хвост о фасовке в названии группы поставщика: «картонная упаковка»,
# «зип-лок», «поштучно». Для раздела это лишнее — фасовка видна в названии.
PACKAGING = re.compile(
    r'\s*(картонная упаковка|пластиковый контейнер|платиковый контейнер|зип-лок|'
    r'поштучно|весовой|дой-пак|упаковки|упаковка|картон|короб|пакет|банка|блистер|'
    r'пластиковое ведро|в ленте|в мотках)\s*$',
    re.I)


def group_name(text):
    name = ' '.join((text or '').split())
    while True:
        cut = PACKAGING.sub('', name)
        if cut == name:
            return name
        name = cut


def main():
    ours = catalog()
    known = {norm(p['title']): p['path'] for p in ours}
    rows = supplier()

    # Голосование по группе поставщика: куда уже отнесены её товары с сайта.
    votes = defaultdict(Counter)
    for row in rows:
        path = known.get(norm(row['NAIMEN']))
        if path:
            votes[(row['PARENTID_NAME1'], row['PARENTID_NAME2'])][path] += 1

    items = [(p['id'], p['sku'], p['title'], p['path']) for p in ours]
    added = 0
    for row in rows:
        if norm(row['NAIMEN']) in known:
            continue
        items.append((row['ID'], row['ARTIKUL'], ' '.join(row['NAIMEN'].split()), route_of(row, votes)))
        added += 1

    items.sort(key=lambda item: (item[3] == UNSORTED, item[3], item[2].lower()))

    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font
    book = Workbook()
    sheet = book.active
    sheet.title = 'Товары'
    sheet.append(['ID', 'Артикул', 'Название', 'Категория'])
    for cell in sheet[1]:
        cell.font = Font(bold=True)
    for item in items:
        sheet.append(list(item))
    for column, width in zip('ABCD', (34, 18, 86, 62)):
        sheet.column_dimensions[column].width = width
    sheet.freeze_panes = 'A2'
    sheet.auto_filter.ref = f'A1:D{len(items) + 1}'
    for row in sheet.iter_rows(min_row=2):
        row[2].alignment = Alignment(wrap_text=False)
    book.save(OUT)

    unsorted_count = sum(1 for item in items if item[3] == UNSORTED)
    print(f'всего строк: {len(items)} (сайт {len(ours)}, из выгрузки поставщика {added})')
    print(f'без раздела: {unsorted_count}')
    print(f'-> {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
