def load_site():
    products = []
    for path in ('src/data/siteCatalogSource.ts', 'src/data/importedFasteners.ts'):
        text = (ROOT / path).read_text(encoding='utf-8')
        starts = [m.start() for m in re.finditer(r'\n\s{2,4}\{\n\s+id:\s*[\'"]', text)]
        for i, a in enumerate(starts):
            chunk = text[a:starts[i + 1] if i + 1 < len(starts) else len(text)]

            def field(key):
                m = re.search(rf'\b{key}:\s*{QUOTED}', chunk)
                return (m.group(1) or m.group(2) or '') if m else ''

            title = field('title')
            if title and not NOT_A_PRODUCT.search(title):
                products.append({'id': field('id'), 'title': title, 'sku': field('sku'),
                                 'sub': field('subcategoryName'),
                                 'descr': field('description'),
                                 # imageLarge крупнее превью -208x208, берём его
                                 'image': field('imageLarge') or field('image')})
    return products


