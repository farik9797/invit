def pull_image(product):
    """Кладёт фото товара в images/ и возвращает имя файла.

    Фото лежат в двух видах: у импортированного крепежа это готовые webp
    в репозитории, у остальных — ссылки на invit.by, то есть собственные
    снимки клиента.
    """
    src = product['image']
    if not src:
        return ''
    name = re.sub(r'[^\w.-]', '_', product['id'] or product['sku'] or 'item')
    try:
        if src.startswith('http'):
            ext = pathlib.Path(src.split('?')[0]).suffix or '.jpg'
            target = IMAGES / f'{name}{ext}'
            if not target.exists():
                data = urllib.request.urlopen(
                    urllib.request.Request(src, headers=UA), timeout=30).read()
                target.write_bytes(data)
        else:
            source = ASSETS / src
            target = IMAGES / f'{name}{pathlib.Path(src).suffix}'
            # Файл мог быть перенесён сюда прежним запуском — тогда исходник
            # уже не нужен, снимок никуда не делся.
            if not target.exists():
                if not source.exists():
                    return ''
                shutil.copy2(source, target)
        return target.name
    except Exception as exc:
        print(f'  фото не получено: {product["title"][:50]} — {exc}')
        return ''


def load_admin(columns, known_sku):
    """Строки из выгрузки админки — она уже в тех же 27 колонках."""
    if not ADMIN.exists():
        print(f'  {ADMIN.name} нет — девятнадцать позиций админки пропущены')
        return []

    with ADMIN.open(encoding='utf-8-sig', newline='') as f:
        rows = [r for r in csv.DictReader(f) if r['product_id'] in FROM_ADMIN]

    out = []
    for row in rows:
        # ЧПУ — тот же ключ, по которому сходятся остальные товары сайта.
        # У трёх позиций его в админке нет, там берём внутренний номер.
        sku = row['URL (ЧПУ)'].strip() or f"INV-{row['product_id']}"
        if sku in known_sku:
            continue
        item = {c: row.get(c, '') for c in columns}
        item.update({
            'Type': 'simple', 'SKU': sku, 'Published': '1',
            'Visibility in catalog': 'visible', 'Tax status': 'taxable',
            'In stock?': '1',
            'Regular price': '',                       # каталог сайта без цен
            'Categories': FROM_ADMIN[row['product_id']],
            'Images': pull_image({'id': sku, 'sku': sku, 'title': row['Name'],
                                  'image': row['Images'].split(', ')[0].strip()}),
            # У админки во втором свойстве модель, у остальной выгрузки — страна.
            # Два разных смысла в одной колонке ломают импорт атрибутов.
            'Attribute 2 name': 'Страна', 'Attribute 2 value(s)': ''
        })
        out.append(item)
    return out


def target_of(product):
    sub, title = product['sub'], product['title'].lower()
    if sub in FIXED:
        return FIXED[sub]
    for pattern, category in BY_TITLE.get(sub, []):
        if re.search(pattern, title):
            return category
    return None


def main():
    with SRC.open(encoding='utf-8-sig', newline='') as f:
        reader = csv.DictReader(f)
        columns, woo = reader.fieldnames, list(reader)

    site = load_site()
    woo_sku = {r['SKU'].strip() for r in woo if r['SKU'].strip()}
    woo_name = {norm(r['Name']) for r in woo}

    added, dups, unmapped = [], [], []
    for p in site:
        if (p['sku'] and p['sku'] in woo_sku) or norm(p['title']) in woo_name:
            dups.append(p)
            continue
        category = target_of(p)
        if not category:
            # обзорные страницы линеек помечаем отдельно — это не товар
            p['landing'] = (p['sub'] == 'Крепёж для окон, кровли, фасадов'
                            and bool(LOOKS_LIKE_LANDING.match(p['title'])))
            unmapped.append(p)
            continue
        added.append((p, category))

    IMAGES.mkdir(exist_ok=True)
    blank = {c: '' for c in columns}
    rows = list(woo)
    for p, category in added:
        p['file'] = pull_image(p)
        rows.append({**blank, **{
            # Без артикула WooCommerce не свяжет вариации с родителем, а часть
            # позиций сайта его не имеет — берём идентификатор товара с сайта.
            'Type': 'simple', 'SKU': p['sku'] or p['id'], 'Name': p['title'],
            'Published': '1', 'Is featured?': '0', 'Visibility in catalog': 'visible',
            'Description': f"<p>{p['descr']}</p>" if p['descr'] else '',
            'Tax status': 'taxable', 'In stock?': '1',
            'Regular price': '',                       # каталог сайта без цен
            'Categories': category, 'Images': p['file'],
            'Attribute 1 name': 'Бренд', 'Attribute 1 value(s)': '',
            'Attribute 1 visible': '1', 'Attribute 1 global': '0',
            'Attribute 2 name': 'Страна', 'Attribute 2 value(s)': '',
            'Attribute 2 visible': '1', 'Attribute 2 global': '0',
        }})

    from_admin = load_admin(columns, {r['SKU'].strip() for r in rows if r['SKU'].strip()})
    rows += from_admin

    with DST.open('w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=columns, lineterminator='\r\n')
        w.writeheader(); w.writerows(rows)

    report = ([{'Что': 'дубль — уже есть в выгрузке', 'Раздел сайта': p['sub'],
                'Название': p['title'][:150], 'Куда': ''} for p in dups] +
              [{'Что': 'добавлен', 'Раздел сайта': p['sub'],
                'Название': p['title'][:150], 'Куда': c} for p, c in added] +
              [{'Что': 'добавлен из админки — на сайте есть, в разборе не было',
                'Раздел сайта': '', 'Название': r['Name'][:150],
                'Куда': r['Categories']} for r in from_admin] +
              [{'Что': ('похоже, страница раздела, а не товар' if p.get('landing')
                         else 'НЕТ РАЗДЕЛА в дереве'),
                'Раздел сайта': p['sub'], 'Название': p['title'][:150], 'Куда': ''}
               for p in unmapped])
    with REPORT.open('w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(report[0]), lineterminator='\r\n')
        w.writeheader(); w.writerows(report)

    print(f'товаров сайта (без сертификатов и новостей): {len(site)}')
    print(f'  дублей с выгрузкой : {len(dups)}')
    print(f'  добавлено          : {len(added)}')
    landing = sum(1 for p in unmapped if p.get('landing'))
    print(f'  некуда положить    : {len(unmapped)}  (из них похожих на страницу раздела: {landing})')
    with_photo = sum(1 for p, _ in added if p['file'])
    print(f'  добавлено из админки: {len(from_admin)} из {len(FROM_ADMIN)}')
    print(f'\nвыгрузка: {len(woo)} → {len(rows)}')
    print(f'фото выгружено: {with_photo} из {len(added)} → {IMAGES}/')
    print('\nнекуда положить, по разделам сайта:')
    for sub, n in Counter(p['sub'] for p in unmapped).most_common():
        print(f'  {n:5}  {sub}')
    return 0


